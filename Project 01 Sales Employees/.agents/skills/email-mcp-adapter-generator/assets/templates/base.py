#!/usr/bin/env python3
"""
base.py — The provider-agnostic email backend interface.

This is the seam that makes the whole architecture portable. send_batch.py
depends only on this interface, never on Hostinger/Gmail/Outlook specifics.
When you switch providers you write ONE new subclass (generated by the
email-mcp-adapter-generator skill) and the rest of the workflow — draft
parsing, 15s pacing, CSV updates, concise reporting — stays byte-for-byte
identical.

A backend has one job: given a recipient, subject, and plain-text body,
send the message and report success or a short failure reason. Everything
provider-specific (endpoint URL, auth header shape, mailbox/resource IDs,
JSON field names) is hidden inside the concrete backend.
"""

from dataclasses import dataclass


@dataclass
class SendResult:
    """Outcome of a single send. `ok` drives the CSV update; `reason`
    is the short human-readable string the agent sees on failure."""
    ok: bool
    reason: str = ""

    @classmethod
    def success(cls):
        return cls(ok=True, reason="")

    @classmethod
    def failure(cls, reason):
        return cls(ok=False, reason=reason)


class EmailBackend:
    """Interface every provider backend implements.

    Concrete backends are constructed with whatever credentials/config
    they need (the token comes from the project-root .env via env_utils),
    then send() is called once per email. Keep send() self-contained and
    synchronous — send_batch.py handles sequencing and the inter-send
    delay, so a backend must NOT sleep or batch internally.
    """

    # Human-readable provider name, e.g. "hostinger". Overridden by subclasses.
    provider = "base"

    # The address mail is sent from, filled in by the backend once known
    # (useful for the run summary). May be None until send() resolves it.
    from_address = None

    def send(self, to, subject, body, display_name=None):
        """Send one plain-text email. Return a SendResult.

        Must not raise for ordinary provider errors (auth, validation,
        rate limit) — catch those and return SendResult.failure(reason)
        so a single bad recipient doesn't abort the whole batch. Raising
        is reserved for programmer errors (misconfiguration) that should
        stop the run.
        """
        raise NotImplementedError
